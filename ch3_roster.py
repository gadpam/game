"""Каноническая заявка и игровые номера «Торпедо-2» для Главы 3.

Ветров играет под номером 19. Номер 8 намеренно никому не назначен в этой
заявке: позже Ветров сам захочет перейти на восьмой номер, но это ещё не
произошло в текущей главе.
"""

STARTERS = (
    "ГРОМОВ",
    "САВЕЛЬЕВ",
    "АНДРЕЕВ",
    "КАРИМОВ",
    "ЛЕВЧУК",
    "ТКАЧЁВ",
    "ВЕТРОВ",
    "ГОНЧАР",
    "НОВИК",
    "МАРЧЕНКО",
    "ДЕНИСОВ",
)

SUBS = (
    "БОБРОВ",
    "МЕЛЬНИК",
    "КИСЕЛЁВ",
    "ШАТСКИЙ",
    "КОВАЛЁВ",
    "РОМАНОВ",
    "ЮРЧЕНКО",
)

SQUAD_NUMBERS = {
    "ГРОМОВ": 1,
    "САВЕЛЬЕВ": 2,
    "АНДРЕЕВ": 3,
    "КАРИМОВ": 4,
    "ЛЕВЧУК": 5,
    "ТКАЧЁВ": 6,
    "ВЕТРОВ": 19,
    "ГОНЧАР": 7,
    "НОВИК": 9,
    "МАРЧЕНКО": 10,
    "ДЕНИСОВ": 11,
    "БОБРОВ": 12,
    "МЕЛЬНИК": 14,
    "КИСЕЛЁВ": 13,
    "ШАТСКИЙ": 16,
    "КОВАЛЁВ": 17,
    "РОМАНОВ": 18,
    "ЮРЧЕНКО": 21,
}

VETROV_NUMBER = 19
VETROV_FUTURE_NUMBER = 8

ALL_PLAYERS = STARTERS + SUBS
assert len(STARTERS) == 11
assert len(SUBS) == 7
assert len(set(ALL_PLAYERS)) == 18
assert set(SQUAD_NUMBERS) == set(ALL_PLAYERS)
assert len(set(SQUAD_NUMBERS.values())) == 18
assert SQUAD_NUMBERS["ВЕТРОВ"] == VETROV_NUMBER
assert VETROV_FUTURE_NUMBER not in SQUAD_NUMBERS.values()
assert "ШАТСКИЙ" in SUBS and "МЕЛЬНИК" in SUBS
